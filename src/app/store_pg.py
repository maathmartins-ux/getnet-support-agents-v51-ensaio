class _Row(dict):
    """Linha que aceita row["coluna"] e row[0], como sqlite3.Row (o store usa os dois)."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description or []]
    return lambda values: _Row(zip(names, values, strict=True))


class _Conn:
    """Fachada mínima de sqlite3.Connection sobre psycopg: execute(sql com `?`, parâmetros) → cursor."""

    def __init__(self, raw: psycopg.Connection) -> None:
        self.raw = raw

    def execute(self, sql: str, params=None):
        if sql.lstrip().upper().startswith("BEGIN"):
            return self.raw.execute("SELECT 1")  # a transação já está aberta (implícita no psycopg)
        if params is None:  # sem parâmetros o psycopg não interpreta `%`: mandar como está
            return self.raw.execute(sql)
        return self.raw.execute(sql.replace("%", "%%").replace("?", "%s"), tuple(params))


class PgStore(Store):
    dialect = "postgres"
    IntegrityError = psycopg.IntegrityError
    NO_LIMIT = "ALL"

    def __init__(self, url: str) -> None:  # noqa: D107 — não chama Store.__init__ (não há arquivo)
        self.path = url  # chave de cache (cases._READY, get_store); nunca exibida (pode ter senha)
        self.url = url
        self._idle: list[psycopg.Connection] = []
        self._pool_lock = threading.Lock()
        self.migrate()

    # --- conexão --------------------------------------------------------------------------------
    def _connect(self) -> psycopg.Connection:
        return psycopg.connect(self.url, connect_timeout=CONNECT_TIMEOUT_S, row_factory=_row_factory)

    def _acquire(self) -> psycopg.Connection:
        with self._pool_lock:
            while self._idle:
                conn = self._idle.pop()
                if not conn.closed:
                    return conn
        return self._connect()

    def _release(self, conn: psycopg.Connection) -> None:
        healthy = not conn.closed and conn.info.transaction_status == TransactionStatus.IDLE
        with self._pool_lock:
            if healthy and len(self._idle) < POOL_IDLE_MAX:
                self._idle.append(conn)
                return
        conn.close()

    @contextmanager
    def _db(self):
        conn = self._acquire()
        try:
            yield _Conn(conn)
            conn.commit()
        except BaseException:
            if not conn.closed:
                conn.rollback()
            raise
        finally:
            self._release(conn)

    def close(self) -> None:
        with self._pool_lock:
            idle, self._idle = self._idle, []
        for conn in idle:
            conn.close()

    # --- esquema --------------------------------------------------------------------------------
    def migrate(self) -> list[int]:
        """Aplica as migrações que faltam, uma vez por esquema, mesmo com réplicas subindo juntas. Devolve as novas."""
        applied: list[int] = []
        with self._connect() as conn:  # conexão própria: DDL e trava na mesma transação
            conn.execute("SELECT pg_advisory_xact_lock(%s, hashtext(current_schema()))", (MIGRATION_LOCK,))
            conn.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY, "
                         "applied_at DOUBLE PRECISION NOT NULL)")
            done = {r["version"] for r in conn.execute("SELECT version FROM schema_version")}
            for version, statements in MIGRATIONS:
                if version in done:
                    continue
                for statement in statements:
                    conn.execute(statement)
                conn.execute("INSERT INTO schema_version (version, applied_at) VALUES (%s, %s)", (version, time.time()))
                applied.append(version)
        return applied

    def schema_version(self) -> int:
        with self._db() as conn:
            return conn.execute("SELECT COALESCE(MAX(version), 0) FROM schema_version").fetchone()[0]

    # --- ganchos de dialeto -----------------------------------------------------------------------
    @staticmethod
    def _begin(conn) -> None:
        """Transação já aberta; READ COMMITTED + UPDATE condicional bastam para apagar/purgar."""

    def _lock_key(self, conn, key: str) -> None:
        # Só a chave do limitador fica serializada (dois réplicas contando "u1" esperam uma a outra; "u2" não espera).
        conn.execute("SELECT pg_advisory_xact_lock(hashtextextended(?, 0))", (f"rate:{key}",))

    def _lock_open(self, conn, key: str) -> None:
        # a mesma trava de `_lock_key` (o apagamento do perfil espera o turno que o está gravando, e vice-versa): no
        # Postgres a transação já está aberta e a trava consultiva vale até o fim dela
        self._lock_key(conn, key)

    @staticmethod
    def _claim_overdue(conn, now: float) -> list[str]:
        # SKIP LOCKED: duas réplicas rodando o laço de SLA ao mesmo tempo pegam linhas diferentes, nenhuma espera a
        # outra, e cada caso sobe de nível uma vez só (o WHERE escalation_level = 0 continua valendo).
        rows = conn.execute(
            "UPDATE tickets SET escalation_level = 1, priority = 'high' WHERE id IN ("
            "SELECT id FROM tickets WHERE status = 'open' AND escalation_level = 0 AND due_at < ? "
            "ORDER BY due_at FOR UPDATE SKIP LOCKED) RETURNING id", (now,))
        return [r["id"] for r in rows]
