"""Backend Postgres do store: a MESMA interface de `store.Store`, para réplicas em mais de um host.

Escolha: DATABASE_URL=postgresql://... (config.database_url). Sem ela, o padrão continua SQLite (ADR 0003).

O que muda em relação ao SQLite, e por quê:
- conexão: psycopg 3, uma por operação tirada de um pool pequeno em memória (abrir conexão TCP a cada chamada
  custa mais que a própria consulta). Transação implícita: commit no fim do bloco, rollback em exceção;
- SQL: o store escreve no subconjunto comum (placeholders `?`, upsert `ON CONFLICT`). `_Conn` só troca `?` por
  `%s` (e escapa `%`); nada de reescrever SQL por regex além disso;
- esquema: migrações VERSIONADAS (tabela schema_version), aplicadas sob trava consultiva da transação: duas réplicas
  subindo juntas não aplicam a mesma migração duas vezes. O SQLite segue com a migração aditiva por coluna;
- disputa: UPDATE condicional continua valendo (no READ COMMITTED a 2ª transação espera a 1ª e reavalia o WHERE,
  rowcount 0). Onde se varre uma fila (SLA vencido), `FOR UPDATE SKIP LOCKED`: réplicas pegam linhas diferentes
  sem se esperar. O limite de uso trava só a chave (pg_advisory_xact_lock), não a tabela;
- auditoria só de inclusão: gatilho que recusa UPDATE, DELETE e TRUNCATE com SQLSTATE 23000 (IntegrityError,
  como no SQLite).
Falha de conexão levanta exceção como qualquer erro de banco: o limitador de uso continua falhando fechado.
"""
